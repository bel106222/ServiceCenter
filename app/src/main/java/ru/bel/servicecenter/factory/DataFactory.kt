     */
    suspend fun setAdminPassword(adminUserId: String, password: String) {
        LoggerService.log("Установка пароля администратора...")
        val hashed = BCrypt.hashpw(password, BCrypt.gensalt())
        // Получаем всех пользователей (в реальном проекте можно добавить метод getUserById)
        val users = RepositoryProvider.userRepo.getAllUsers()
        val admin = users.firstOrNull { it.id == adminUserId }
            ?: throw IllegalStateException("Пользователь admin не найден")
        val updatedAdmin = admin.copy(user_password = hashed)
        RepositoryProvider.userRepo.updateUser(updatedAdmin)
        LoggerService.log("Пароль администратора успешно установлен")
    }
